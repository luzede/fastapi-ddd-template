"""Stable machine-readable error codes emitted by the auth module.

Names follow better-auth's `BASE_ERROR_CODES`, `ADMIN_ERROR_CODES` and `API_KEY_ERROR_CODES`
so clients ported from better-auth can keep their error handling.
"""

