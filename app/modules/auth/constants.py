    INVALID_REMAINING = "INVALID_REMAINING"
    NO_VALUES_TO_UPDATE = "NO_VALUES_TO_UPDATE"
    KEY_MISSING_PERMISSIONS = "KEY_MISSING_PERMISSIONS"

    # jwt plugin
    JWKS_NOT_AVAILABLE = "JWKS_NOT_AVAILABLE"
