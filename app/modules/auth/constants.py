    BANNED_USER = "BANNED_USER"
    NOT_IMPERSONATING = "NOT_IMPERSONATING"

    # api key plugin
    INVALID_API_KEY = "INVALID_API_KEY"
    KEY_NOT_FOUND = "KEY_NOT_FOUND"
    KEY_DISABLED = "KEY_DISABLED"
    KEY_EXPIRED = "KEY_EXPIRED"
    USAGE_EXCEEDED = "USAGE_EXCEEDED"
    RATE_LIMITED = "RATE_LIMITED"
    KEY_NOT_RECOVERABLE = "KEY_NOT_RECOVERABLE"
    INVALID_NAME_LENGTH = "INVALID_NAME_LENGTH"
    INVALID_PREFIX_LENGTH = "INVALID_PREFIX_LENGTH"
    EXPIRES_IN_IS_TOO_SMALL = "EXPIRES_IN_IS_TOO_SMALL"
